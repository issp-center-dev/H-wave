"""Golden-file regression for the pre-tail static-Eliashberg path.

The critical invariant of the bond-channels PR is that a user who does not ask
for anything new gets exactly the files they got before.  The bond-path tests
in ``tests/test_sc_bond.py`` compare two runs of the *same* (post-change)
build, which can only catch a difference between ``bond_channels`` absent and
``bond_channels = false`` -- it cannot see a change that both runs share.

This module compares against bytes produced **at commit 712b1a0**, the merge
commit this branch was cut from, i.e. genuine pre-change output.  The fixtures
live in ``tests/sc/legacy_golden/`` and were generated by the recipe in
``tests/sc/legacy_golden/generate_golden.py`` (git worktree at 712b1a0).

``chi0q`` is *loaded* from the committed ``chi0q.npz`` rather than recomputed:
``sc._calc_chi0q_internal`` is not bit-reproducible run to run (~1e-14 ULP
jitter, issue #85). Develop now shares a momentum-reversal helper across the
solvers, so the physical gap is compared at round-off tolerance.

The golden eigenvalue turned out to be a non-converged power-iteration
artefact (a sign-alternating two-cycle of a negative dominant eigenvalue, see
``TestByteForByteAgainstPreBranchOutput``). Since the solver stopped reporting
such numbers (NaN with ``eigen_converged = false``), the golden is no longer
byte-compared; the tests pin what it is instead.

Tests must be run from the repository root (fixture paths are relative).
"""
import importlib.util
import os
import shutil
import tempfile
import unittest

import numpy as np

import hwave.sc as sc


GOLDEN_DIR = os.path.join("tests", "sc", "legacy_golden")


def _load_generator():
    """Import the golden generator so the test uses the IDENTICAL config."""
    path = os.path.join(GOLDEN_DIR, "generate_golden.py")
    spec = importlib.util.spec_from_file_location("_legacy_golden_gen", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _run_legacy(outdir, **eli_overrides):
    """Run the legacy configuration in ``outdir`` and return the raw bytes."""
    os.makedirs(outdir, exist_ok=True)
    shutil.copy(os.path.join(GOLDEN_DIR, "chi0q.npz"),
                os.path.join(outdir, "chi0q.npz"))
    input_dict = _load_generator().build_input(outdir)
    # develop now defaults to the analytic G2 tail correction. This fixture
    # pins the pre-correction 712b1a0 stream, so opt out explicitly.
    input_dict["eliashberg"]["g2_tail"] = False
    input_dict["eliashberg"].update(eli_overrides)
    sc.calc_eliashberg(input_dict)
    out = {}
    for name in ("eigenvalue.dat", "gap.dat"):
        with open(os.path.join(outdir, name), "rb") as f:
            out[name] = f.read()
    return out


def _golden(name):
    with open(os.path.join(GOLDEN_DIR, name), "rb") as f:
        return f.read()


def _assert_gap_matches_golden(got):
    np.testing.assert_allclose(
        np.loadtxt(got.splitlines()),
        np.loadtxt(_golden("gap.dat").splitlines()),
        rtol=0.0, atol=1.0e-12)


def _gap_vector(raw):
    rows = np.loadtxt(raw.splitlines())
    return rows[:, 3] + 1j * rows[:, 4]


def _eigenvalue_value(raw):
    lines = [l for l in raw.decode().splitlines() if not l.startswith("#")]
    return float(lines[0])


class TestByteForByteAgainstPreBranchOutput(unittest.TestCase):
    """What the 712b1a0 golden actually is, and what the solver reports now.

    The golden configuration (``solver_mode = "iteration"``, no
    ``spectral_shift``, ``max_iter = 40``, ``alpha = 0.5``) runs the power
    iteration on a kernel whose dominant eigenvalue is NEGATIVE
    (-2.75244786). The iterate settles into a sign-alternating two-cycle of
    amplitude s = (1 - alpha)/(1 + alpha) = 1/3, and the golden
    ``9.17482619e-01`` is ``|lambda_-| * s`` -- not an eigenvalue. The solver
    no longer reports it: a non-converged iteration writes NaN with
    ``eigen_converged = false``.
    """

    def setUp(self):
        self.tmp_path = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp_path, ignore_errors=True)

    def test_golden_value_is_the_two_cycle_artefact(self):
        got = _run_legacy(os.path.join(self.tmp_path, "run"),
                          spectral_shift="none")
        text = got["eigenvalue.dat"].decode()
        self.assertIn("# eigen_converged = false", text)
        self.assertIn("two-cycle", text)
        self.assertTrue(np.isnan(_eigenvalue_value(got["eigenvalue.dat"])))
        # the dominant (negative) eigenvalue, from the eigenvalue solver
        ev = _run_legacy(os.path.join(self.tmp_path, "ev"),
                         solver_mode="eigenvalue", num_eigenvalues=6)
        rows = np.array([[float(x) for x in l.split()[:2]]
                         for l in ev["eigenvalue.dat"].decode().splitlines()
                         if l.strip() and not l.startswith("#")][1:])
        lam_minus = rows[np.argmax(np.abs(rows[:, 1])), 1]
        self.assertLess(lam_minus, 0.0)
        golden = _eigenvalue_value(_golden("eigenvalue.dat"))
        self.assertAlmostEqual(golden, abs(lam_minus) / 3.0, delta=1.0e-7)

    def test_golden_gap_is_the_cycling_iterate(self):
        """The written gap is still the cycling iterate (the eigenvector of
        the negative dominant mode), now normalized: equal to the golden gap
        up to the amplitude s = 1/3 and a phase."""
        for overrides in ({"spectral_shift": "none"},
                          {"spectral_shift": "none", "bond_channels": False}):
            with self.subTest(**overrides):
                got = _run_legacy(os.path.join(self.tmp_path, "run"),
                                  **overrides)
                a = _gap_vector(got["gap.dat"])
                b = _gap_vector(_golden("gap.dat"))
                self.assertAlmostEqual(np.linalg.norm(b), 1.0 / 3.0,
                                       delta=1.0e-8)
                ph = np.vdot(a, b) / abs(np.vdot(a, b))
                np.testing.assert_allclose(
                    a / np.linalg.norm(a) * ph, b / np.linalg.norm(b),
                    rtol=0.0, atol=1.0e-7)

    def test_default_run_never_reports_the_artefact(self):
        """The default (spectral_shift "auto") does not converge in the
        golden's 40 steps: NaN and eigen_converged = false, not a number."""
        got = _run_legacy(os.path.join(self.tmp_path, "run"))
        self.assertIn("# eigen_converged = false",
                      got["eigenvalue.dat"].decode())
        self.assertTrue(np.isnan(_eigenvalue_value(got["eigenvalue.dat"])))

    def test_legacy_eigenvalue_dat_carries_no_comment_beyond_the_header(self):
        """Pins WHAT the golden is, so a future regeneration cannot quietly
        launder new comment lines into the baseline."""
        text = _golden("eigenvalue.dat").decode()
        comments = [l for l in text.splitlines() if l.startswith("#")]
        self.assertEqual(comments, ["# Iteration eigenvalue"])


class TestInformativeNoteStillAppears(unittest.TestCase):
    """The informative note must still appear when it carries information."""

    def setUp(self):
        self.tmp_path = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp_path, ignore_errors=True)

    def test_spectral_shift_run_does_emit_the_note(self):
        """The note is suppressed only when it says nothing; an explicit
        ``spectral_shift`` changes the MEANING of the number, so it must be
        labelled."""
        got = _run_legacy(os.path.join(self.tmp_path, "run"),
                          spectral_shift="auto")
        text = got["eigenvalue.dat"].decode()
        self.assertIn("spectral_shift", text)
        self.assertNotEqual(got["eigenvalue.dat"], _golden("eigenvalue.dat"))


class TestCalcG2MovedToBondChannels(unittest.TestCase):
    """_calc_g2 moved to bond_channels._g2_from_green -- prove it did not
    change."""

    @staticmethod
    def _calc_g2_pre_branch(green_kw, beta):
        """Verbatim copy of ``sc._calc_g2`` as of commit 712b1a0."""
        norb = green_kw.shape[0]
        Nx, Ny, Nz, nmat = (green_kw.shape[2], green_kw.shape[3],
                            green_kw.shape[4], green_kw.shape[5])
        nvol = Nx * Ny * Nz

        green_kw_inv = np.roll(
            green_kw[:, :, ::-1, ::-1, ::-1, ::-1],
            (1, 1, 1), (2, 3, 4)
        )
        A = green_kw.reshape(norb * norb, nvol, nmat)
        B = green_kw_inv.reshape(norb * norb, nvol, nmat)
        As = np.moveaxis(A, 1, 0)
        Bs = np.moveaxis(B, 1, 0)
        G2 = np.moveaxis(As @ Bs.transpose(0, 2, 1), 0, 2)
        G2 = G2.reshape(norb, norb, norb, norb, Nx, Ny, Nz)
        return G2 / beta

    def test_calc_g2_is_bit_identical_to_the_pre_branch_implementation(self):
        """``sc._calc_g2`` now delegates to
        ``bond_channels._g2_from_green``; the result must be bit-for-bit what
        the pre-branch inline implementation produced."""
        for shape in [(1, 1, 4, 4, 1, 16), (2, 2, 3, 2, 2, 8)]:
            with self.subTest(shape=shape):
                rng = np.random.default_rng(11)
                green = (rng.normal(size=shape) + 1j * rng.normal(size=shape))
                beta = 3.7
                got = sc._calc_g2(green, beta, tail=False)
                ref = self._calc_g2_pre_branch(green, beta)
                self.assertEqual(got.dtype, ref.dtype)
                self.assertEqual(got.shape, ref.shape)
                self.assertTrue(np.array_equal(got, ref))


class TestShiftedRunLabelsEigenvalueFile(unittest.TestCase):
    """A shifted run must say in the FILE whether its number is an
    eigenvalue (and write NaN when it is not)."""

    def setUp(self):
        self.tmp_path = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp_path, ignore_errors=True)

    def test_unvalidated_shifted_run_is_labelled_in_eigenvalue_dat(self):
        """Too few iterations to converge: eigenvalue.dat must say there is
        no eigenvalue (NaN, eigen_converged = false)."""
        got = _run_legacy(os.path.join(self.tmp_path, "run"),
                          spectral_shift=1.0, max_iter=2)
        text = got["eigenvalue.dat"].decode()
        self.assertIn("NOT an eigenvalue", text)
        self.assertIn("eigen_converged = false", text)
        self.assertTrue(np.isnan(_eigenvalue_value(got["eigenvalue.dat"])))

    def test_validated_shifted_run_is_labelled_as_a_signed_eigenvalue(self):
        got = _run_legacy(os.path.join(self.tmp_path, "run"),
                          spectral_shift="auto", max_iter=2000)
        text = got["eigenvalue.dat"].decode()
        self.assertIn("SIGNED eigenvalue", text)
        self.assertIn("VALIDATED", text)
        self.assertIn("# eigen_converged = true", text)


if __name__ == "__main__":
    unittest.main()
